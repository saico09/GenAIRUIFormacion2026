-- Migración idempotente. Antes de aplicarla sobre datos existentes, conservar un pg_dump.
-- Las dos APIs empaquetan este SQL; se serializa incluso si arrancan a la vez.
BEGIN;
SELECT pg_advisory_xact_lock(71420261107);
SELECT pg_advisory_xact_lock(71420261109);

CREATE TABLE IF NOT EXISTS public.patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    birth_date DATE NOT NULL,
    email VARCHAR(320) NOT NULL
);

DO $migration$
DECLARE
    canonical_sequence TEXT;
    legacy_sequence TEXT;
    canonical_high BIGINT := 0;
    legacy_high BIGINT := 0;
    patient_high BIGINT := 0;
BEGIN
    canonical_sequence := pg_get_serial_sequence('public.patients', 'id');
    IF canonical_sequence IS NULL THEN
        RAISE EXCEPTION 'public.patients.id requiere una secuencia; no se cambia un esquema desconocido';
    END IF;
    EXECUTE format('SELECT CASE WHEN is_called THEN last_value ELSE last_value - 1 END FROM %s', canonical_sequence)
        INTO canonical_high;
    IF to_regclass('java.patients') IS NOT NULL THEN
        IF EXISTS (
            SELECT 1 FROM public.patients p JOIN java.patients j USING (id)
            WHERE (p.name, p.birth_date, p.email) IS DISTINCT FROM (j.name, j.birth_date, j.email)
        ) THEN
            RAISE EXCEPTION 'Pacientes Python/Java con el mismo ID y distinta identidad: se requiere conciliación; no se sobrescribió nada';
        END IF;
        legacy_sequence := pg_get_serial_sequence('java.patients', 'id');
        IF legacy_sequence IS NOT NULL THEN
            EXECUTE format('SELECT CASE WHEN is_called THEN last_value ELSE last_value - 1 END FROM %s', legacy_sequence)
                INTO legacy_high;
        END IF;
        INSERT INTO public.patients (id, name, birth_date, email)
            SELECT j.id, j.name, j.birth_date, j.email FROM java.patients j
            WHERE NOT EXISTS (SELECT 1 FROM public.patients p WHERE p.id = j.id);
        DROP TABLE java.patients;
    END IF;
    SELECT COALESCE(MAX(id), 0) INTO patient_high FROM public.patients;
    patient_high := greatest(patient_high, canonical_high, legacy_high);
    IF patient_high > canonical_high THEN
        PERFORM setval(canonical_sequence::regclass, greatest(patient_high, 1), patient_high > 0);
    END IF;

    IF to_regclass('java.medical_consultations') IS NOT NULL THEN
        IF to_regclass('public.medical_consultations') IS NOT NULL THEN
            RAISE EXCEPTION 'Hay dos tablas medical_consultations; se requiere conciliación para conservar ambas';
        END IF;
        ALTER TABLE java.medical_consultations SET SCHEMA public;
    END IF;
END
$migration$;

-- Las filas clínicas y los UUID son los mismos que muestra el informe Markdown.
CREATE TABLE IF NOT EXISTS public.patient_diseases (
    id UUID PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    disease TEXT NOT NULL DEFAULT '',
    treatment TEXT NOT NULL DEFAULT '',
    medication TEXT NOT NULL DEFAULT '',
    CONSTRAINT patient_diseases_has_content CHECK (
        btrim(disease) <> '' OR btrim(treatment) <> '' OR btrim(medication) <> '')
);
CREATE INDEX IF NOT EXISTS patient_diseases_patient_id ON public.patient_diseases(patient_id);

-- El historial conserva consultas y revisiones completas, incluso tras borrar un paciente.
CREATE TABLE IF NOT EXISTS public.medical_consultations (
    id UUID PRIMARY KEY,
    execution_id UUID NOT NULL,
    patient_id INTEGER NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('consultation', 'snapshot', 'deleted')),
    question TEXT,
    direct_answer TEXT,
    rag_answer TEXT,
    model TEXT,
    sources JSONB NOT NULL DEFAULT '[]'::jsonb,
    filename TEXT NOT NULL,
    markdown_content TEXT NOT NULL,
    revision VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE public.medical_consultations
    ADD COLUMN IF NOT EXISTS storage_order BIGINT GENERATED ALWAYS AS IDENTITY;
CREATE INDEX IF NOT EXISTS medical_consultations_patient_created
    ON public.medical_consultations(patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS medical_consultations_patient_order
    ON public.medical_consultations(patient_id, storage_order DESC);

-- Un UUID por operación HTTP. patient_id no tiene FK: también identifica pacientes borrados.
CREATE TABLE IF NOT EXISTS public.transaction_logs (
    id UUID PRIMARY KEY,
    patient_id INTEGER,
    service TEXT NOT NULL CHECK (service IN ('python', 'java')),
    operation TEXT NOT NULL,
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    http_status INTEGER NOT NULL,
    request_body TEXT NOT NULL DEFAULT '',
    response_body TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    duration_ms DOUBLE PRECISION NOT NULL,
    request_truncated BOOLEAN NOT NULL DEFAULT FALSE,
    response_truncated BOOLEAN NOT NULL DEFAULT FALSE
);
ALTER TABLE public.transaction_logs ADD COLUMN IF NOT EXISTS patient_id INTEGER;
-- Sólo se atribuye el paciente cuando la ruta/cuerpo guardado lo identifica sin ambigüedad.
UPDATE public.transaction_logs
SET patient_id = substring(path FROM '^(?:/clinical)?/patients/([0-9]+)(?:/|$)')::integer
WHERE patient_id IS NULL AND path ~ '^(?:/clinical)?/patients/[0-9]+(?:/|$)'
    AND substring(path FROM '^(?:/clinical)?/patients/([0-9]+)(?:/|$)')::numeric BETWEEN 1 AND 2147483647;
UPDATE public.transaction_logs
SET patient_id = CASE WHEN pg_input_is_valid(response_body, 'jsonb') THEN
    CASE WHEN response_body::jsonb ->> 'id' ~ '^[0-9]{1,10}$' THEN
        CASE WHEN (response_body::jsonb ->> 'id')::numeric BETWEEN 1 AND 2147483647
            THEN (response_body::jsonb ->> 'id')::integer END END END
WHERE patient_id IS NULL AND path = '/patients' AND method = 'POST'
    AND http_status = 201;
UPDATE public.transaction_logs
SET patient_id = CASE WHEN pg_input_is_valid(request_body, 'jsonb') THEN
    CASE WHEN request_body::jsonb ->> 'patient_id' ~ '^[0-9]{1,10}$' THEN
        CASE WHEN (request_body::jsonb ->> 'patient_id')::numeric BETWEEN 1 AND 2147483647
            THEN (request_body::jsonb ->> 'patient_id')::integer END END END
WHERE patient_id IS NULL AND path IN ('/chat', '/clinical/proposals');
ALTER TABLE public.transaction_logs DROP COLUMN IF EXISTS execution_id;
ALTER TABLE public.transaction_logs DROP COLUMN IF EXISTS request_id;
CREATE INDEX IF NOT EXISTS transaction_logs_patient_id ON public.transaction_logs(patient_id);
COMMIT;
